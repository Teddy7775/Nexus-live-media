/** Breadcrumb HTML */
function breadcrumbs(array $items): string {
  $out = '<nav class="crumbs" aria-label="Breadcrumb"><ol>';
  $n = count($items); $i = 0;
  foreach ($items as $name => $path) {
    $i++;
    $out .= $i === $n ? '<li aria-current="page">' . h($name) . '</li>' : '<li><a href="' . h($path) . '">' . h($name) . '</a></li>';
  }
  return $out . '</ol></nav>';
}

/** FAQ accordion from [[q,a],...] or [['q'=>..,'a'=>..],...] */
function faq_list(array $faqs, string $class = ''): string {
  $out = '<div class="faq ' . h($class) . '">';
  foreach ($faqs as $f) {
    $q = isset($f['q']) ? $f['q'] : $f[0];
    $a = isset($f['a']) ? $f['a'] : $f[1];
    $out .= '<details class="faq-item"><summary><span>' . h($q) . '</span>' . icon('chevron', 'faq-chev') . '</summary><div class="faq-body"><p>' . h($a) . '</p></div></details>';
  }
  return $out . '</div>';
}

