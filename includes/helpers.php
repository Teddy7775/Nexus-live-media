function ld_breadcrumb(array $items): array {
  $list = [];
  $i = 1;
  foreach ($items as $name => $path) {
    $list[] = ['@type' => 'ListItem', 'position' => $i++, 'name' => $name, 'item' => site_url($path)];
  }
  return ['@context' => 'https://schema.org', '@type' => 'BreadcrumbList', 'itemListElement' => $list];
}

function ld_faq(array $faqs): array {
  $q = [];
  foreach ($faqs as $f) {
    $question = is_array($f) && isset($f['q']) ? $f['q'] : $f[0];
    $answer   = is_array($f) && isset($f['a']) ? $f['a'] : $f[1];
    $q[] = ['@type' => 'Question', 'name' => $question, 'acceptedAnswer' => ['@type' => 'Answer', 'text' => $answer]];
  }
  return ['@context' => 'https://schema.org', '@type' => 'FAQPage', 'mainEntity' => $q];
}

