function h(?string $s): string {
  return htmlspecialchars((string)$s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

function site_url(string $path = ''): string {
  return rtrim(SITE_URL, '/') . '/' . ltrim($path, '/');
}

/** Cache-busted asset URL: /assets/css/site.css?v=abcd1234 */
function asset(string $path): string {
  $file = dirname(__DIR__) . '/' . ltrim($path, '/');
  $v = is_file($file) ? substr(md5((string)filemtime($file)), 0, 8) : '1';
  return '/' . ltrim($path, '/') . '?v=' . $v;
}

/** Current clean path, e.g. "/services/led-screen-rental" or "/" */
function current_path(): string {
  $p = (string)(parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?: '/');
  $p = preg_replace('~\.php$~', '', $p) ?? '/';
  $p = rtrim($p, '/');
  if ($p === '' || $p === '/index') return '/';
  return $p;
}

function is_active(string $href): bool {
  $cur = current_path();
  if ($href === '/') return $cur === '/';
  return $cur === $href || str_starts_with($cur, $href . '/');
}

