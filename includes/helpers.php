// ---- Signed, stateless form token (no PHP session needed) ----
function form_token(): string {
  $ts  = (string)time();
  $sig = hash_hmac('sha256', $ts, form_secret());
  return $ts . '.' . $sig;
}
/** Returns '' when valid, otherwise a short reason code */
function form_token_check(string $token): string {
  if (!preg_match('/^(\d{9,11})\.([a-f0-9]{64})$/', $token, $m)) return 'format';
  $ts = (int)$m[1];
  $expected = hash_hmac('sha256', $m[1], form_secret());
  if (!hash_equals($expected, $m[2])) return 'signature';
  $age = time() - $ts;
  if ($age < FORM_MIN_SECONDS) return 'too-fast';
  if ($age > FORM_MAX_SECONDS) return 'expired';
  return '';
}

