// Files are generated by tools/optimize-images.mjs as {base}-{width}.jpg / .webp
function picture(string $base, string $alt, array $o = []): string {
  $root   = dirname(__DIR__) . '/assets/img/';
  $widths = $o['widths'] ?? [800, 1600];
  $avail  = array_values(array_filter($widths, fn($w) => is_file("{$root}{$base}-{$w}.jpg")));
  $class  = isset($o['class']) ? ' class="' . h($o['class']) . '"' : '';
  $loading = $o['loading'] ?? 'lazy';
  $prio   = isset($o['priority']) && $o['priority'] ? ' fetchpriority="high"' : '';
  $sizes  = $o['sizes'] ?? '(max-width: 768px) 100vw, 50vw';

  if (!$avail) {
    // Plain single file (e.g. legacy photo-booth-tiers.jpg) or a placeholder while images are missing
    $single = "{$root}{$base}.jpg";
    if (is_file($single)) {
      [$w, $hgt] = getimagesize($single) ?: [0, 0];
      return "<img src=\"/assets/img/{$base}.jpg\" alt=\"" . h($alt) . "\" width=\"{$w}\" height=\"{$hgt}\" loading=\"{$loading}\" decoding=\"async\"{$class}{$prio}>";
    }
    return '<div class="img-placeholder"' . ($class ? ' data-class="' . h($o['class']) . '"' : '') . ' role="img" aria-label="' . h($alt) . '"></div>';
  }

  $largest = max($avail);
  [$w, $hgt] = getimagesize("{$root}{$base}-{$largest}.jpg") ?: [0, 0];
  $jpg  = implode(', ', array_map(fn($x) => "/assets/img/{$base}-{$x}.jpg {$x}w", $avail));
  $webp = array_values(array_filter($avail, fn($x) => is_file("{$root}{$base}-{$x}.webp")));
  $out  = '<picture>';
  if ($webp) {
    $ws = implode(', ', array_map(fn($x) => "/assets/img/{$base}-{$x}.webp {$x}w", $webp));
    $out .= "<source type=\"image/webp\" srcset=\"{$ws}\" sizes=\"" . h($sizes) . "\">";
  }
  $out .= "<img src=\"/assets/img/{$base}-{$largest}.jpg\" srcset=\"{$jpg}\" sizes=\"" . h($sizes) . "\" alt=\"" . h($alt) . "\" width=\"{$w}\" height=\"{$hgt}\" loading=\"{$loading}\" decoding=\"async\"{$class}{$prio}>";
  $out .= '</picture>';
  return $out;
}

/** Absolute URL of the largest generated variant, for og:image */
function image_url(string $base, int $pref = 1600): string {
  $root = dirname(__DIR__) . '/assets/img/';
  foreach ([$pref, 1920, 1280, 800] as $w) {
    if (is_file("{$root}{$base}-{$w}.jpg")) return site_url("assets/img/{$base}-{$w}.jpg");
  }
  return site_url("assets/img/{$base}.jpg");
}

